/**
 * Mirrors the nitrogen-generated view config into `src/` as a TypeScript module.
 *
 * Why this exists: `src/NitroListHost.ts` used to import the config straight from
 * `../nitrogen/generated/shared/json/NitroListViewConfig.json`, which escapes bob's
 * source root. bob copies relative specifiers verbatim into `lib/module/` and
 * `lib/commonjs/`, where `../` resolves to `lib/` instead of the package root — so
 * the published build could not resolve it at all (see verify-build's
 * `assertRelativeImportsResolve`).
 *
 * Keeping the config inside `src/` makes the specifier depth-independent. Emitting
 * TypeScript rather than copying the JSON also means consumers never need `json` in
 * their bundler's `sourceExts` to load this package.
 *
 * Usage:
 *   node scripts/sync-view-config.mjs           # write src/generated/nitroListViewConfig.ts
 *   node scripts/sync-view-config.mjs --check   # exit 1 if the mirror is stale
 */
import {existsSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, relative, resolve, sep} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const SOURCE_JSON = join(
  root,
  'nitrogen',
  'generated',
  'shared',
  'json',
  'NitroListViewConfig.json',
);
export const TARGET_TS = join(root, 'src', 'generated', 'nitroListViewConfig.ts');

const posix = (absolute) => relative(root, absolute).split(sep).join('/');

const SAFE_KEY = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

const quote = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function emit(value, depth) {
  const pad = '  '.repeat(depth);
  const padInner = '  '.repeat(depth + 1);

  if (value === null) return 'null';
  if (typeof value === 'string') return quote(value);
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);

  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    const entries = value.map((entry) => `${padInner}${emit(entry, depth + 1)}`);
    return `[\n${entries.join(',\n')},\n${pad}]`;
  }

  const keys = Object.keys(value);
  if (keys.length === 0) return '{}';
  const entries = keys.map((key) => {
    const label = SAFE_KEY.test(key) ? key : quote(key);
    return `${padInner}${label}: ${emit(value[key], depth + 1)}`;
  });
  return `{\n${entries.join(',\n')},\n${pad}}`;
}

export function renderViewConfigModule() {
  if (!existsSync(SOURCE_JSON)) {
    throw new Error(`missing ${posix(SOURCE_JSON)} — run \`nitrogen\` before syncing`);
  }

  const config = JSON.parse(readFileSync(SOURCE_JSON, 'utf8'));

  return [
    `// AUTO-GENERATED by scripts/sync-view-config.mjs — DO NOT EDIT.`,
    `// Mirrors ${posix(SOURCE_JSON)}.`,
    `//`,
    `// The config is mirrored into src/ on purpose: importing it from ../nitrogen/`,
    `// escapes bob's source root, and bob copies relative specifiers verbatim into`,
    `// lib/module and lib/commonjs, where ../ no longer points at the package root.`,
    ``,
    `export const NitroListViewConfig = ${emit(config, 0)};`,
    ``,
  ].join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const expected = renderViewConfigModule();
  const actual = existsSync(TARGET_TS) ? readFileSync(TARGET_TS, 'utf8') : null;

  if (actual === expected) {
    console.log(`view config in sync — ${posix(TARGET_TS)}`);
    return;
  }

  if (check) {
    console.error(
      `${posix(TARGET_TS)} is out of sync with ${posix(SOURCE_JSON)}.\n` +
        `Run \`node scripts/sync-view-config.mjs\` and commit the result.`,
    );
    process.exit(1);
  }

  mkdirSync(dirname(TARGET_TS), {recursive: true});
  writeFileSync(TARGET_TS, expected);
  console.log(`${actual == null ? 'created' : 'updated'} ${posix(TARGET_TS)}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
